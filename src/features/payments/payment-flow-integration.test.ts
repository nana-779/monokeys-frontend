import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { prepareTestOrder, type DevTestOrder } from './test-order-preparation'
import { createPaymentRequester, type PaymentRequest } from './payment-request'
import { createPaymentConfirmationClient } from './payment-confirmation'
import { createResultFlow, resultHeading } from './payment-result-flow'
import { mountOrderWidgets } from './order-widget-rendering'

type Case = { scenario: string; created: { data: DevTestOrder }; lookup: { data: DevTestOrder }
  request: { paymentKey: string; orderId: string; amount: number }; responses: { status: number; body: unknown }[] }
// Generated by the backend MockMvc test, not manually copied example responses.
const contract = JSON.parse(readFileSync(new URL('../../back-2nd-project-git/build/stage10/contract.json', import.meta.url), 'utf8')) as { version: number; cases: Case[] }
assert.equal(contract.version, 1)

for (const fixture of contract.cases) test('Spring controller -> frontend complete mock flow: ' + fixture.scenario, async () => {
  const amounts: unknown[] = [], renders: string[] = [], sdk: PaymentRequest[] = []
  let attempt: string | null = null, transports = 0
  const widgets = {
    setAmount: async (value: unknown) => { amounts.push(value) },
    renderPaymentMethods: async ({ selector }: { selector: string }) => { renders.push(selector); return { destroy: async () => {} } },
    renderAgreement: async ({ selector }: { selector: string }) => { renders.push(selector); return { destroy: async () => {} } },
  }
  const order = await prepareTestOrder(widgets, { create: async () => fixture.created.data,
    find: async () => fixture.lookup.data }, new AbortController().signal)
  assert.deepEqual(amounts, [{ currency: 'KRW', value: order.amount }])
  const mounted = mountOrderWidgets(widgets, { payment: '#methods', agreement: '#terms' }); await mounted.ready
  assert.deepEqual(renders, ['#methods', '#terms'])
  const request = createPaymentRequester({ find: async () => fixture.lookup.data,
    remember: value => { attempt = JSON.stringify(value) }, request: async value => { sdk.push(value) } })
  const input = { order, ready: true, clientKey: 'test_gck_fixture_only', origin: 'http://localhost:3000', signal: new AbortController().signal }
  await request(input); await assert.rejects(request(input)); assert.equal(sdk.length, 1)
  assert.equal(sdk[0].orderId, order.orderId); assert.equal(sdk[0].orderName, order.orderName)
  assert.equal(sdk[0].successUrl, 'http://localhost:3000/dev/toss-order/success')
  assert.equal(sdk[0].failUrl, 'http://localhost:3000/dev/toss-order/fail')
  const confirm = createPaymentConfirmationClient('http://localhost:8080', async (url, init) => {
    assert.equal(url, 'http://localhost:8080/api/payments/confirm'); assert.equal(init.credentials, 'include')
    assert.deepEqual(JSON.parse(init.body as string), fixture.request)
    const response = fixture.responses[transports++]; assert.ok(response)
    return { status: response.status, json: async () => response.body }
  })
  const params = new URLSearchParams({ paymentKey: fixture.request.paymentKey, orderId: order.orderId, amount: String(order.amount) })
  const expectedFirst = fixture.scenario === 'REJECTED' ? 'confirmation-failed'
    : fixture.scenario === 'WAITING_FOR_DEPOSIT' ? 'waiting-for-deposit'
      : fixture.scenario === 'DONE' ? 'approved' : 'confirmation-unknown'
  const first = await createResultFlow(async () => fixture.lookup.data, confirm)(params, attempt)
  assert.equal(first.phase, expectedFirst)
  if (first.phase !== 'approved') assert.notEqual(resultHeading('success', first), '테스트 결제 완료')
  // Recreating the flow models a refreshed callback consumer, not an actual browser reload.
  const replay = await createResultFlow(async () => fixture.lookup.data, confirm)(params, attempt)
  assert.equal(replay.phase, ['REJECTED', 'WAITING_FOR_DEPOSIT'].includes(fixture.scenario) ? expectedFirst : 'approved')
  assert.equal(transports, 2)
  assert.ok(!JSON.stringify([first, replay]).includes(fixture.request.paymentKey))
  await mounted.dispose()
})

test('tampered/missing/duplicate callback fields never reach transport using backend-created order', async () => {
  const fixture = contract.cases[0], order = fixture.created.data
  let posts = 0
  const confirm = createPaymentConfirmationClient('http://localhost:8080', async () => { posts++; throw new Error('must not send') })
  for (const field of ['paymentKey', 'orderId', 'amount']) {
    const p = new URLSearchParams({ ...fixture.request, amount: String(order.amount) })
    p.append(field, 'tampered')
    assert.equal((await createResultFlow(async () => order, confirm)(p, JSON.stringify(order))).phase, 'invalid-result')
    p.delete(field)
    assert.equal((await createResultFlow(async () => order, confirm)(p, JSON.stringify(order))).phase, 'invalid-result')
  }
  const changedAmount = new URLSearchParams({ ...fixture.request, amount: String(order.amount + 1) })
  assert.equal((await createResultFlow(async () => order, confirm)(changedAmount, JSON.stringify(order))).phase, 'invalid-result')
  assert.equal(posts, 0)
})
